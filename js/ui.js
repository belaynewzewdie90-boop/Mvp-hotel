function toast(message, type = "info") {
  let region = document.getElementById("toastRegion");
  if (!region) {
    region = document.createElement("div");
    region.id = "toastRegion";
    document.body.appendChild(region);
  }

  const icon = type === "success" ? Icons.check : type === "error" ? Icons.alert : Icons.bell;
  const el = document.createElement("div");
  el.className = `toast toast-${type}`;
  el.innerHTML = `${icon}<span>${message}</span>`;
  region.appendChild(el);

  setTimeout(() => {
    el.classList.add("toast-out");
    el.addEventListener("animationend", () => el.remove(), { once: true });
  }, 2600);
}

function confirmModal({ title, message, confirmText = "Delete", danger = true }) {
  return new Promise((resolve) => {
    const backdrop = document.createElement("div");
    backdrop.className = "modal-backdrop";
    backdrop.innerHTML = `
      <div class="modal" role="dialog" aria-modal="true">
        <h3>${title}</h3>
        <p>${message}</p>
        <div class="modal-actions">
          <button class="btn" data-act="cancel">Cancel</button>
          <button class="btn ${danger ? "btn-danger" : "btn-primary"}" data-act="ok">${confirmText}</button>
        </div>
      </div>`;

    const close = (result) => {
      backdrop.remove();
      resolve(result);
    };

    backdrop.addEventListener("click", (e) => {
      if (e.target === backdrop) close(false);
      const act = e.target.closest("[data-act]");
      if (act) close(act.dataset.act === "ok");
    });
    document.body.appendChild(backdrop);
  });
}

function statusBadge(status) {
  return `<span class="badge badge-${status}"><span class="badge-dot"></span>${status}</span>`;
}

function formatSAR(value) {
  return `${Number(value || 0).toFixed(2)} SAR`;
}

function timeAgo(iso) {
  const then = new Date(iso).getTime();
  if (Number.isNaN(then)) return "";
  const seconds = Math.floor((Date.now() - then) / 1000);
  if (seconds < 60) return "just now";
  const mins = Math.floor(seconds / 60);
  if (mins < 60) return `${mins}m ago`;
  const hours = Math.floor(mins / 60);
  return `${hours}h ${mins % 60}m ago`;
}

/* Re-render across open tabs when data changes. */
function liveRefresh(render) {
  window.addEventListener("storage", (e) => {
    if (e.key === DB.storageKey) render();
  });
}

/* Escape HTML inserted into templates. */
function esc(value) {
  return String(value ?? "").replace(
    /[&<>"']/g,
    (c) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c],
  );
}

/* Reload when the page is restored from the Back-Forward Cache, so
   Live Server's WebSocket reconnects and data stays fresh. */
window.addEventListener("pageshow", (e) => {
  if (e.persisted) window.location.reload();
});
